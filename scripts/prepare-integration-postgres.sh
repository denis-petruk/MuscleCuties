#!/usr/bin/env bash
# Provision the disposable local PostgreSQL fixtures used by the integration and latency suites.
# Loopback only. Creates no secrets and refuses non-local hosts.
set -euo pipefail
cd "$(dirname "$0")/.."

PGHOST="${PGHOST:-127.0.0.1}"
PGPORT="${PGPORT:-5432}"
PGUSER="${PGUSER:-$(whoami)}"
SEED_DB="${MC_SEED_DB:-mc_test_nutrition_seeded}"
RETRY_DB="${MC_RETRY_DB:-mc_retry_disposable}"
PG09_DB="${MC_PG09_DB:-mc_pg09_disposable}"
ROLE="${MC_PG09_ROLE:-mc_pg09_migrator}"
ENV_FILE="${MC_TEST_ENV_FILE:-.env.integration}"

case "$PGHOST" in
  127.0.0.1|localhost) ;;
  *) echo "Refusing non-loopback PostgreSQL host: $PGHOST" >&2; exit 2 ;;
esac
command -v psql >/dev/null || { echo "psql is required (PostgreSQL 16 client/server)." >&2; exit 2; }
pg_isready -h "$PGHOST" -p "$PGPORT" >/dev/null || {
  echo "PostgreSQL is not accepting connections on $PGHOST:$PGPORT." >&2
  echo "Start it first, e.g. brew services start postgresql@16." >&2
  exit 2
}

PSQL=(psql -h "$PGHOST" -p "$PGPORT" -U "$PGUSER" -v ON_ERROR_STOP=1)
"${PSQL[@]}" -d postgres <<SQL
DO \$\$ BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = '$ROLE') THEN
    CREATE ROLE "$ROLE" LOGIN CREATEROLE NOSUPERUSER NOBYPASSRLS;
  END IF;
END \$\$;
ALTER ROLE "$ROLE" LOGIN CREATEROLE NOSUPERUSER NOBYPASSRLS;
SQL

dropdb -h "$PGHOST" -p "$PGPORT" -U "$PGUSER" --if-exists --force "$SEED_DB" 2>/dev/null || true
createdb -h "$PGHOST" -p "$PGPORT" -U "$PGUSER" "$SEED_DB"

# Use the repository's own seed harness so the schema, security SQL and canonical data match production bootstrap.
MC_PREPARE_DISPOSABLE_WORKOUT_DATABASE=True \
MC_REGISTRATION_WRITE_TEST_POSTGRES="Host=$PGHOST;Port=$PGPORT;Database=$SEED_DB;Username=$PGUSER" \
DOTNET_CLI_USE_MSBUILD_SERVER=0 MSBUILDDISABLENODEREUSE=1 \
dotnet test tests/MuscleCuties.Registration.Integration.Tests/MuscleCuties.Registration.Integration.Tests.csproj \
  -c Debug -m:1 --filter "FullyQualifiedName~InitializeAndSeedExplicitlySelectedDisposableDatabase" >/dev/null

dropdb -h "$PGHOST" -p "$PGPORT" -U "$PGUSER" --if-exists --force "$RETRY_DB" 2>/dev/null || true
createdb -h "$PGHOST" -p "$PGPORT" -U "$PGUSER" "$RETRY_DB"
dropdb -h "$PGHOST" -p "$PGPORT" -U "$PGUSER" --if-exists --force "$PG09_DB" 2>/dev/null || true
createdb -h "$PGHOST" -p "$PGPORT" -U "$PGUSER" -T "$SEED_DB" "$PG09_DB"

"${PSQL[@]}" -d "$PG09_DB" <<SQL
ALTER DATABASE "$PG09_DB" OWNER TO "$ROLE";
GRANT ALL ON DATABASE "$PG09_DB" TO "$ROLE";
DO \$\$ DECLARE r record; BEGIN
  FOR r IN SELECT schemaname, tablename FROM pg_tables WHERE schemaname IN ('app','public') LOOP
    EXECUTE format('ALTER TABLE %I.%I OWNER TO %I', r.schemaname, r.tablename, '$ROLE');
  END LOOP;
  FOR r IN SELECT schemaname, sequencename FROM pg_sequences WHERE schemaname IN ('app','public') LOOP
    EXECUTE format('ALTER SEQUENCE %I.%I OWNER TO %I', r.schemaname, r.sequencename, '$ROLE');
  END LOOP;
END \$\$;
GRANT USAGE, CREATE ON SCHEMA public, app, catalog TO "$ROLE";
GRANT ALL ON ALL TABLES IN SCHEMA app, public TO "$ROLE";
GRANT ALL ON ALL SEQUENCES IN SCHEMA app, public TO "$ROLE";
GRANT SELECT ON ALL TABLES IN SCHEMA catalog TO "$ROLE";
GRANT USAGE ON SCHEMA catalog TO "$ROLE";
SQL

cat > "$ENV_FILE" <<EOF
# Generated by scripts/prepare-integration-postgres.sh for local disposable tests. No secrets.
# Source this file from a fresh shell before running the PostgreSQL-backed suites.
export MC_INTEGRATION_POSTGRES=1
export MC_REGISTRATION_WRITE_TEST_POSTGRES='Host=$PGHOST;Port=$PGPORT;Database=$SEED_DB;Username=$PGUSER'
export MC_REGISTRATION_TEST_POSTGRES='Host=$PGHOST;Port=$PGPORT;Database=$SEED_DB;Username=$PGUSER'
export MC_SCHEMA_COMPATIBILITY_POSTGRES='Host=$PGHOST;Port=$PGPORT;Database=$SEED_DB;Username=$PGUSER'
export MC_PG09_LOAD_POSTGRES='Host=$PGHOST;Port=$PGPORT;Database=$PG09_DB;Username=$ROLE'
export MC_RETRY_TEST_POSTGRES='Host=$PGHOST;Port=$PGPORT;Database=$RETRY_DB;Username=$PGUSER'
export MC_LATENCY_POSTGRES='Host=$PGHOST;Port=$PGPORT;Database=$SEED_DB;Username=$PGUSER'
