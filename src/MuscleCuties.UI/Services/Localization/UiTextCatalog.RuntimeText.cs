    public static string TranslateRuntimeText(string english)
    {
        if (string.IsNullOrEmpty(english) ||
            LocalizationService.ActiveLanguage != LocalizationService.RussianLanguageCode)
        {
            return english;
        }

        if (TryResolveRuntimeValue(english, out var translated))
            return translated;

        foreach (var pattern in RuntimeFormats)
        {
            var match = pattern.Matcher.Match(english);
            if (!match.Success)
                continue;

            var values = match.Groups.Cast<Group>().Skip(1)
                .Select(group => TryResolveRuntimeValue(group.Value, out var resolved) ? resolved : group.Value)
                .ToArray();
            return string.Format(CultureInfo.CurrentCulture, pattern.Russian, values);
        }

        return english;
    }

    private static bool TryResolveRuntimeValue(string english, out string russian)
    {
        if (RuntimeRussian.TryGetValue(english, out russian!))
            return true;

        if (AuthoredKeyByEnglish.TryGetValue(english, out var key) &&
            RussianUiText.Values.TryGetValue(key, out russian!))
        {
            return true;
        }

        russian = english;
        return false;
    }

    private static RuntimePattern NewRuntimePattern(string english, string russian)
    {
        var pieces = Regex.Split(english, @"\{\d+\}");
        var regex = "^" + string.Join("(.+?)", pieces.Select(Regex.Escape)) + "$";
        return new RuntimePattern(new Regex(regex, RegexOptions.CultureInvariant), russian);
    }

    private static RuntimePattern NewNumericRuntimePattern(string english, string russian)
    {
        var pieces = Regex.Split(english, @"\{\d+\}");
        var regex = "^" + string.Join(@"(\d+(?:[.,]\d+)?)", pieces.Select(Regex.Escape)) + "$";
        return new RuntimePattern(new Regex(regex, RegexOptions.CultureInvariant), russian);
    }

    private sealed record RuntimePattern(Regex Matcher, string Russian);
